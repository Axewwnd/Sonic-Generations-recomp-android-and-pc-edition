// Shader cache entry - matches XenosRecomp generated format
struct ShaderCacheEntry {
    uint64_t hash; // XXH3 hash of Xbox360 bytecode
    const uint32_t* spirv; // SPIR-V bytecode (Vulkan)
    size_t spirvSize; // Size in bytes
    const uint8_t* dxil; // DXIL bytecode (D3D12)
    size_t dxilSize;
    uint32_t stage; // 0 = vertex, 1 = pixel
    std::string name; // Debug name
};

// Precompiled shader cache - loads from shader_cache.cpp generated by XenosRecomp
class ShaderCache {
public:
    static ShaderCache& Get();
    
    bool Initialize(const char* cachePath = nullptr);
    void Shutdown();
    
    // Find shader in cache by hash
    const ShaderCacheEntry* Find(uint64_t hash) const;
    
    // Load from generated C++ file (shader_cache.cpp)
    bool LoadFromGeneratedCache();
    
    // Load from disk cache (for incremental updates)
    bool LoadFromDisk(const char* path);
    bool SaveToDisk(const char* path) const;
    
    // Stats
    struct Stats {
        uint64_t totalShaders = 0;
        uint64_t cacheHits = 0;
        uint64_t cacheMisses = 0;
        size_t memoryUsage = 0;
    };
    const Stats& GetStats() const { return stats_; }
    
    // For debugging: dump cache info
    void DumpInfo() const;
    
    // Check if cache contains all 6404 shaders for Generations
    bool IsComplete() const { return entries_.size() >= 6404; }
    
private:
    ShaderCache() = default;
    
    std::unordered_map<uint64_t, ShaderCacheEntry> entries_;
    Stats stats_;
    bool initialized_ = false;
};

